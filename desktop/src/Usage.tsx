function Ring({
  value,
  size = 112,
  stroke = 11,
  color,
  label,
}: {
  value: number;
  size?: number;
  stroke?: number;
  color: string;
  label?: string;
}) {
  const r = (size - stroke) / 2;
  const c = 2 * Math.PI * r;
  const clamped = Math.max(0, Math.min(1, value));
  return (
    <div className="usage-ring" style={{ width: size, height: size }}>
      <svg width={size} height={size}>
        <circle
          cx={size / 2}
          cy={size / 2}
          r={r}
          fill="none"
          stroke="var(--border)"
          strokeWidth={stroke}
        />
        <circle
          cx={size / 2}
          cy={size / 2}
          r={r}
          fill="none"
          stroke={color}
          strokeWidth={stroke}
          strokeDasharray={String(c * clamped) + " " + String(c)}
          strokeLinecap="round"
          transform={"rotate(-90 " + String(size / 2) + " " + String(size / 2) + ")"}
        />
        <text x="50%" y="49%" textAnchor="middle" className="usage-ring-value">
          {Math.round(clamped * 100) + "%"}
        </text>
        {label && (
          <text x="50%" y="64%" textAnchor="middle" className="usage-ring-label">
            {label}
          </text>
        )}
      </svg>
    </div>
  );
}

interface DayPoint {
  key: string;
  label: string;
  prompt: number;
  cacheRead: number;
  hit: number;
}

function TrendChart({ days }: { days: DayPoint[] }) {
  const W = 720;
  const H = 190;
  const left = 34;
  const right = 14;
  const top = 14;
  const bottom = 26;
  const max = Math.max(1, ...days.map((d) => d.prompt));
  const slot = (W - left - right) / days.length;
  const bw = Math.max(6, slot * 0.58);
  const points = days
    .map((d, i) => {
      const x = left + (i + 0.5) * slot;
      const y = top + (H - top - bottom) * (1 - d.hit);
      return String(x) + "," + String(y);
    })
    .join(" ");
  return (
    <svg viewBox={"0 0 " + String(W) + " " + String(H)} className="usage-trend" role="img">
      {[0, 0.25, 0.5, 0.75, 1].map((g) => (
        <line
          key={g}
          x1={left}
          x2={W - right}
          y1={top + (H - top - bottom) * g}
          y2={top + (H - top - bottom) * g}
          className="usage-grid"
        />
      ))}
      {days.map((d, i) => {
        const x = left + i * slot + (slot - bw) / 2;
        const h = (H - top - bottom) * (d.prompt / max);
        const cached = d.prompt > 0 ? h * (d.cacheRead / d.prompt) : 0;
        return (
          <g key={d.key}>
            <rect
              x={x}
              y={H - bottom - h}
              width={bw}
              height={h}
              rx={3}
              className="usage-bar-uncached"
            >
              <title>{d.label + ": " + fmtTokens(d.prompt) + " prompt"}</title>
            </rect>
            <rect
              x={x}
              y={H - bottom - cached}
              width={bw}
              height={cached}
              rx={3}
              className="usage-bar-cached"
            >
              <title>{d.label + ": " + fmtTokens(d.cacheRead) + " cache read"}</title>
            </rect>
            {i % 2 === 0 && (
              <text x={x + bw / 2} y={H - 8} textAnchor="middle" className="usage-axis">
                {d.label}
              </text>
            )}
          </g>
        );
      })}
      <polyline points={points} className="usage-hit-line" />
      {days.map((d, i) => {
        const x = left + (i + 0.5) * slot;
        const y = top + (H - top - bottom) * (1 - d.hit);
        return <circle key={d.key} cx={x} cy={y} r={2.2} className="usage-hit-dot" />;
      })}
    </svg>
  );
}

function ServerCard({
  profiles,
  profileId,
  onProfileChange,
  compact,
  copy,
}: {
  profiles: ProfileView[];
  profileId: string;
  onProfileChange?: (id: string) => void;
  compact?: boolean;
  copy: Copy;
}) {
  const [stats, setStats] = useState<ServerCacheStats | null>(null);
  const [loading, setLoading] = useState(false);

  const profile = profiles.find((p) => p.id === profileId);
  const isLocal =
    !!profile && /vllm|openai-compatible|openai/.test(profile.provider_type);
  const options = profiles.filter(
    (p) => p.base_url && /vllm|openai-compatible|openai/.test(p.provider_type),
  );

  useEffect(() => {
    if (!profileId || !isLocal) return;
    let cancelled = false;
    setStats(null);
    const run = async () => {
      setLoading(true);
      try {
        const next = await api.getServerCache(profileId);
        if (!cancelled) setStats(next);
      } catch (e) {
        if (!cancelled) {
          setStats({
            ok: false,
            message: errorMessage(e),
            endpoint: "",
            hits: 0,
            queries: 0,
            hit_rate: 0,
            kv_usage: 0,
            running: 0,
          });
        }
      } finally {
        if (!cancelled) setLoading(false);
      }
    };
    void run();
    const id = window.setInterval(() => void run(), 12000);
    return () => {
      cancelled = true;
      window.clearInterval(id);
    };
  }, [profileId, isLocal]);

  return (
    <section className={"usage-card usage-server-card" + (compact ? " compact" : "")}>
      <div className="usage-card-head">
        <div>
          <h3>{copy.serverTitle}</h3>
          <p>{copy.serverSub}</p>
        </div>
        {onProfileChange && options.length > 0 && (
          <select
            className="usage-select"
            value={profileId}
            onChange={(e) => onProfileChange(e.target.value)}
            aria-label={copy.serverTitle}
          >
            {options.map((p) => (
              <option key={p.id} value={p.id}>
                {p.name}
              </option>
            ))}
          </select>
        )}
      </div>

      {!profileId ? (
        <p className="usage-empty-inline">{copy.serverNoProfile}</p>
      ) : !isLocal ? (
        <p className="usage-empty-inline">{copy.serverLocalOnly}</p>
      ) : stats === null ? (
        <div className="usage-server-loading">
          <div className="usage-spinner" />
          <span>{loading ? copy.loading : ""}</span>
        </div>
      ) : !stats.ok ? (
        <div className="usage-server-down">
          <span className="usage-warn-dot">!</span>
          <div>
            <strong>{copy.serverDown}</strong>
            <p className="mono">{stats.endpoint || profile?.base_url}</p>
            <p className="muted">{stats.message}</p>
          </div>
        </div>
      ) : (
        <div className="usage-server-body">
          <Ring
            value={stats.hit_rate}
            size={compact ? 96 : 122}
            stroke={compact ? 9 : 11}
            color={hitColor(stats.hit_rate)}
            label={copy.colHit}
          />
          <div className="usage-server-stats">
            <div>
              <span>{copy.serverHits}</span>
              <strong>
                {fmtTokens(stats.hits)} <em>/</em> {fmtTokens(stats.queries)}
              </strong>
            </div>
            <div>
              <span>{copy.serverKv}</span>
              <strong>{fmtPercent(stats.kv_usage)}</strong>
            </div>
            <div>
              <span>{copy.serverRunning}</span>
              <strong>{Math.round(stats.running)}</strong>
            </div>
          </div>
        </div>
      )}
    </section>
  );
}

function SessionDrawer({
  row,
  profiles,
  copy,
  lang,
  onClose,
}: {
  row: Row;
  profiles: ProfileView[];
  copy: Copy;
  lang: "zh" | "en";
  onClose: () => void;
}) {
  const { usage, session } = row;
  const all = usage.total_prompt_tokens + usage.output_tokens;
  const segments = [
    { key: "cache", label: copy.statCacheRead, value: usage.cache_read_tokens, cls: "cache" },
    { key: "input", label: copy.inputLabel, value: usage.input_tokens, cls: "input" },
    { key: "create", label: copy.cacheWriteLabel, value: usage.cache_creation_tokens, cls: "create" },
    { key: "output", label: copy.outputLabel, value: usage.output_tokens, cls: "output" },
  ];
  const turns = usage.per_turn.slice(-30);
  const maxTurn = Math.max(
    1,
    ...turns.map((x) => x.input_tokens + x.cache_creation_tokens + x.cache_read_tokens),
  );

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") onClose();
    };
    window.addEventListener("keydown", onKey);
    const previous = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    return () => {
      window.removeEventListener("keydown", onKey);
      document.body.style.overflow = previous;
    };
  }, [onClose]);

  return (
    <div className="usage-drawer-overlay" onClick={onClose}>
      <aside className="usage-drawer" onClick={(e) => e.stopPropagation()}>
        <div className="usage-drawer-head">
          <div>
            <p className="usage-eyebrow">
              {session.profile_name} · {session.engine === "claude" ? "Claude" : "Codex"}
            </p>
            <h2>{session.title || session.preview || usage.session_id.slice(0, 8)}</h2>
          </div>
          <button type="button" className="usage-close" onClick={onClose} aria-label="close">
            ✕
          </button>
        </div>

        <div className="usage-drawer-hero">
          <Ring
            value={usage.cache_hit_rate}
            size={128}
            color={hitColor(usage.cache_hit_rate)}
            label={copy.colHit}
          />
          <div className="usage-drawer-kpis">
            <div>
              <span>{copy.statPrompt}</span>
              <strong>{fmtTokens(usage.total_prompt_tokens)}</strong>
            </div>
            <div>
              <span>{copy.statCacheRead}</span>
              <strong>{fmtTokens(usage.cache_read_tokens)}</strong>
            </div>
            <div>
              <span>{copy.statOutput}</span>
              <strong>{fmtTokens(usage.output_tokens)}</strong>
            </div>
            <div>
              <span>{copy.colTurns}</span>
              <strong>{usage.turns}</strong>
            </div>
          </div>
        </div>

        <h3 className="usage-drawer-section">{copy.drawerComposition}</h3>
        <div className="usage-composition" aria-hidden>
          {segments.map((s) => (
            <div
              key={s.key}
              className={"usage-comp-seg " + s.cls}
              style={{ width: String(all > 0 ? (s.value / all) * 100 : 0) + "%" }}
              title={s.label + ": " + fmtTokens(s.value)}
            />
          ))}
        </div>
        <div className="usage-legend">
          {segments.map((s) => (
            <span key={s.key}>
              <i className={s.cls} />
              {s.label} <strong>{fmtTokens(s.value)}</strong>
            </span>
          ))}
        </div>

        <h3 className="usage-drawer-section">{copy.drawerTurns}</h3>
        {turns.length === 0 ? (
          <p className="muted">{copy.drawerNoTurns}</p>
        ) : (
          <div className="usage-turn-chart">
            {turns.map((x, i) => {
              const p = x.input_tokens + x.cache_creation_tokens + x.cache_read_tokens;
              const h = Math.max(4, (p / maxTurn) * 100);
              const cached = p > 0 ? x.cache_read_tokens / p : 0;
              const when = x.timestamp ? new Date(x.timestamp * 1000).toLocaleString() : "—";
              return (
                <div
                  key={x.timestamp + "-" + i}
                  className="usage-turn-col"
                  title={when + " · " + fmtTokens(p) + " prompt · " + fmtPercent(cached) + " cache"}
                >
                  <div className="usage-turn-bar" style={{ height: String(h) + "%" }}>
                    <div className="usage-turn-cache" style={{ height: String(cached * 100) + "%" }} />
                  </div>
                </div>
              );
            })}
          </div>
        )}

        <div className="usage-drawer-section">
          <ServerCard profiles={profiles} profileId={usage.profile_id} compact copy={copy} />
        </div>

        {usage.cache_read_tokens === 0 && <p className="usage-gateway-note">{copy.gatewayNote}</p>}
        <p className="usage-drawer-meta">
          {new Date((usage.modified || session.modified) * 1000).toLocaleString()} ·{" "}
          {timeAgo(usage.modified || session.modified, lang)}
        </p>
      </aside>
    </div>
  );
}

export default function UsagePage({ profiles }: Props) {
  const { lang } = useI18n();
  const copy: Copy = lang === "zh" ? ZH : EN;

  const [sessions, setSessions] = useState<Session[] | null>(null);
  const [usage, setUsage] = useState<SessionUsage[] | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [range, setRange] = useState<"all" | "7d" | "30d">("all");
  const [profileFilter, setProfileFilter] = useState("all");
  const [engineFilter, setEngineFilter] = useState("all");
  const [search, setSearch] = useState("");
  const [selected, setSelected] = useState<Row | null>(null);
  const [serverProfileId, setServerProfileId] = useState("");
  const [exporting, setExporting] = useState(false);
  const [exportNote, setExportNote] = useState<{ text: string; ok: boolean } | null>(null);
  const loadSeq = useRef(0);

  const load = useCallback(async (showLoading = false) => {
    const seq = ++loadSeq.current;
    if (showLoading) setLoading(true);
    try {
      const [nextSessions, nextUsage] = await Promise.all([
        api.listSessions(),
        api.listSessionUsage(),
      ]);
      if (seq !== loadSeq.current) return;
      setSessions(nextSessions);
      setUsage(nextUsage);
      setError(null);
    } catch (e) {
      if (seq === loadSeq.current) setError(errorMessage(e));
    } finally {
      if (seq === loadSeq.current) setLoading(false);
    }
  }, []);

  const exportCsv = useCallback(async () => {
    try {
      const path = await save({
        defaultPath: "agent-switch-usage.csv",
        filters: [{ name: "CSV", extensions: ["csv"] }],
      });
      if (!path) return;
      setExporting(true);
      const result = await api.exportUsageCsv(path);
      setExportNote({
        text: copy.exportDone + " " + result.rows + " rows · " + result.path,
        ok: true,
      });
    } catch (e) {
      setExportNote({ text: copy.exportFailed + ": " + errorMessage(e), ok: false });
    } finally {
      setExporting(false);
    }
  }, [copy.exportDone, copy.exportFailed]);

  useEffect(() => {
    void load(true);
    const id = window.setInterval(() => void load(false), 12000);
    return () => window.clearInterval(id);
  }, [load]);

  useEffect(() => {
    if (serverProfileId) return;
    const local = profiles.filter((p) => /vllm|openai-compatible|openai/.test(p.provider_type));
    const pick = local[0] ?? profiles.find((p) => p.base_url) ?? profiles[0];
    if (pick) setServerProfileId(pick.id);
  }, [profiles, serverProfileId]);

  const rows = useMemo<Row[]>(() => {
    if (!sessions || !usage) return [];
    const byId = new Map(sessions.map((s) => [s.session_id, s]));
    const out: Row[] = [];
    for (const u of usage) {
      const s = byId.get(u.session_id);
      if (s) out.push({ session: s, usage: u });
    }
    return out;
  }, [sessions, usage]);

  const filtered = useMemo(() => {
    const now = Math.floor(Date.now() / 1000);
    const q = search.trim().toLowerCase();
    return rows
      .filter(({ session, usage: u }) => {
        if (profileFilter !== "all" && u.profile_id !== profileFilter) return false;
        if (engineFilter !== "all" && u.engine !== engineFilter) return false;
        if (range !== "all") {
          const days = range === "7d" ? 7 : 30;
          if ((u.modified || session.modified) < now - days * 86400) return false;
        }
        if (q) {
          const hay = (
            (session.title ?? "") +
            " " +
            session.preview +
            " " +
            session.profile_name +
            " " +
            u.model +
            " " +
            u.session_id
          ).toLowerCase();
          if (!hay.includes(q)) return false;
        }
        return true;
      })
      .sort(
        (a, b) =>
          (b.usage.modified || b.session.modified) - (a.usage.modified || a.session.modified),
      );
  }, [rows, profileFilter, engineFilter, range, search]);

  const totals = useMemo(() => {
    let prompt = 0;
    let cacheRead = 0;
    let input = 0;
    let output = 0;
    let cacheCreate = 0;
    let turns = 0;
    for (const { usage: u } of filtered) {
      prompt += u.total_prompt_tokens;
      cacheRead += u.cache_read_tokens;
      input += u.input_tokens;
      output += u.output_tokens;
      cacheCreate += u.cache_creation_tokens;
      turns += u.turns;
    }
    return {
      prompt,
      cacheRead,
      input,
      output,
      cacheCreate,
      turns,
      hit: prompt > 0 ? cacheRead / prompt : 0,
    };
  }, [filtered]);

  const days = useMemo<DayPoint[]>(() => {
    const list: DayPoint[] = [];
    const now = new Date();
    for (let i = 13; i >= 0; i--) {
      const d = new Date(now);
      d.setDate(now.getDate() - i);
      d.setHours(0, 0, 0, 0);
      list.push({
        key: d.getFullYear() + "-" + (d.getMonth() + 1) + "-" + d.getDate(),
        label: d.getMonth() + 1 + "/" + d.getDate(),
        prompt: 0,
        cacheRead: 0,
        hit: 0,
      });
    }
    const index = new Map(list.map((d, i) => [d.key, i]));
    for (const { usage: u } of filtered) {
      for (const turn of u.per_turn) {
        if (!turn.timestamp) continue;
        const d = new Date(turn.timestamp * 1000);
        const key = d.getFullYear() + "-" + (d.getMonth() + 1) + "-" + d.getDate();
        const i = index.get(key);
        if (i === undefined) continue;
        list[i].prompt += turn.input_tokens + turn.cache_creation_tokens + turn.cache_read_tokens;
        list[i].cacheRead += turn.cache_read_tokens;
      }
    }
    for (const d of list) {
      d.hit = d.prompt > 0 ? d.cacheRead / d.prompt : 0;
    }
    return list;
  }, [filtered]);

  const profileOptions = useMemo(() => {
    const ids = new Set(rows.map((r) => r.usage.profile_id));
    return profiles.filter((p) => ids.has(p.id));
  }, [rows, profiles]);

  useEffect(() => {
    if (!selected) return;
    const next = rows.find((r) => r.usage.session_id === selected.usage.session_id);
    if (next) setSelected(next);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [rows]);

  const showGatewayBanner = filtered.length > 0 && totals.cacheRead === 0;

  return (
    <div className="usage-page">
      <div className="usage-header">
        <div>
          <p className="usage-eyebrow">Agent Switch</p>
          <h1>{copy.title}</h1>
          <p className="usage-subtitle">{copy.subtitle}</p>
        </div>
        <div className="usage-actions">
          <div className="usage-range" role="group">
            {(["all", "7d", "30d"] as const).map((r) => (
              <button
                key={r}
                type="button"
                className={range === r ? "active" : ""}
                onClick={() => setRange(r)}
              >
                {r === "all" ? copy.rangeAll : r === "7d" ? copy.range7 : copy.range30}
              </button>
            ))}
          </div>
          <button
            type="button"
            className="btn secondary small"
            onClick={() => void exportCsv()}
            disabled={exporting}
            title={copy.exportHint}
          >
            {exporting ? copy.exporting : copy.exportCsv}
          </button>
          <button
            type="button"
            className="btn secondary small"
            onClick={() => void load(true)}
            disabled={loading}
          >
            {loading ? copy.loading : copy.refresh}
          </button>
        </div>
      </div>

      {error && (
        <div className="usage-error">
          {copy.errorPrefix}: {error}
        </div>
      )}

      {exportNote && (
        <div className={"usage-export-note" + (exportNote.ok ? "" : " error")}>
          <span>{exportNote.text}</span>
          <button type="button" onClick={() => setExportNote(null)} aria-label="dismiss">
            ✕
          </button>
        </div>
      )}

      {showGatewayBanner && (
        <div className="usage-banner">
          <div className="usage-banner-icon">i</div>
          <div>
            <strong>{copy.bannerTitle}</strong>
            <p>{copy.bannerBody}</p>
          </div>
        </div>
      )}

      <div className="usage-stats-grid">
        <StatCard
          label={copy.statPrompt}
          value={fmtTokens(totals.prompt)}
          sub={copy.statPromptSub + " · " + fmtTokens(totals.input) + " uncached"}
          icon="tokens"
        />
        <StatCard
          label={copy.statCacheRead}
          value={fmtTokens(totals.cacheRead)}
          sub={fmtPercent(totals.hit) + " · " + copy.statCacheReadSub}
          icon="cache"
          tone={totals.cacheRead > 0 ? hitTone(totals.hit) : undefined}
        />
        <StatCard
          label={copy.statOutput}
          value={fmtTokens(totals.output)}
          sub={copy.statOutputSub}
          icon="output"
        />
        <StatCard
          label={copy.statSessions}
          value={filtered.length + " / " + totals.turns}
          sub={copy.statSessionsSub}
          icon="sessions"
        />
      </div>

      <div className="usage-main-grid">
        <section className="usage-card usage-trend-card">
          <div className="usage-card-head">
            <div>
              <h3>{copy.trendTitle}</h3>
              <p>{copy.trendSub}</p>
            </div>
            <div className="usage-legend-inline">
              <span>
                <i className="uncached" />
                {copy.trendLegendPrompt}
              </span>
              <span>
                <i className="cached" />
                {copy.trendLegendCache}
              </span>
              <span>
                <i className="line" />
                {copy.trendLegendHit}
              </span>
            </div>
          </div>
          <TrendChart days={days} />
        </section>

        <ServerCard
          profiles={profiles}
          profileId={serverProfileId}
          onProfileChange={setServerProfileId}
          copy={copy}
        />
      </div>

      <section className="usage-card usage-table-card">
        <div className="usage-card-head usage-table-head">
          <div>
            <h3>{copy.tableTitle}</h3>
            <p>{copy.tableSub}</p>
          </div>
          <div className="usage-filters">
            <input
              className="usage-search"
              placeholder={copy.searchPlaceholder}
              value={search}
              onChange={(e) => setSearch(e.target.value)}
            />
            <select
              className="usage-select"
              value={profileFilter}
              onChange={(e) => setProfileFilter(e.target.value)}
            >
              <option value="all">{copy.allProfiles}</option>
              {profileOptions.map((p) => (
                <option key={p.id} value={p.id}>
                  {p.name}
                </option>
              ))}
            </select>
            <select
              className="usage-select"
              value={engineFilter}
              onChange={(e) => setEngineFilter(e.target.value)}
            >
              <option value="all">{copy.allEngines}</option>
              <option value="claude">Claude</option>
              <option value="codex">Codex</option>
            </select>
          </div>
        </div>

        {usage === null ? (
          <div className="usage-skeleton">
            {[0, 1, 2, 3, 4].map((i) => (
              <div key={i} className="usage-skeleton-row" />
            ))}
          </div>
        ) : filtered.length === 0 ? (
          <div className="usage-empty">
            <div className="usage-empty-icon">
              <Icon name="cache" />
            </div>
            <strong>{copy.emptyTitle}</strong>
            <p>{copy.emptyBody}</p>
          </div>
        ) : (
          <div className="usage-table-wrap">
            <table className="usage-table">
              <thead>
                <tr>
                  <th>{copy.colSession}</th>
                  <th>{copy.colModel}</th>
                  <th className="num">{copy.colTokens}</th>
                  <th>{copy.colHit}</th>
                  <th className="num">{copy.colTurns}</th>
                  <th>{copy.colTime}</th>
                </tr>
              </thead>
              <tbody>
                {filtered.map(({ session, usage: u }) => {
                  const tone = hitTone(u.cache_hit_rate);
                  return (
                    <tr
                      key={u.session_id}
                      tabIndex={0}
                      onClick={() => setSelected({ session, usage: u })}
                      onKeyDown={(e) => {
                        if (e.key === "Enter" || e.key === " ") {
                          e.preventDefault();
                          setSelected({ session, usage: u });
                        }
                      }}
                    >
                      <td>
                        <div className="usage-session-cell">
                          <span className={"usage-dot " + session.engine} />
                          <div>
                            <strong>
                              {session.title || session.preview || u.session_id.slice(0, 8)}
                            </strong>
                            <span>
                              {session.profile_name} ·{" "}
                              {session.engine === "claude" ? "Claude" : "Codex"}
                            </span>
                          </div>
                        </div>
                      </td>
                      <td>
                        <span className="usage-model" title={u.model || session.profile_name}>
                          {u.model || "—"}
                        </span>
                      </td>
                      <td className="num">
                        <span className="usage-token-main">{fmtTokens(u.input_tokens)}</span>
                        <span className="usage-token-cache">
                          {" "}
                          / {fmtTokens(u.cache_read_tokens)} /{" "}
                        </span>
                        <span>{fmtTokens(u.output_tokens)}</span>
                      </td>
                      <td>
                        <span className={"usage-hit-badge " + tone}>
                          <i />
                          {fmtPercent(u.cache_hit_rate)}
                        </span>
                      </td>
                      <td className="num">{u.turns}</td>
                      <td>
                        <span className="usage-time">
                          {timeAgo(u.modified || session.modified, lang)}
                        </span>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )}
      </section>

      {selected && (
        <SessionDrawer
          row={selected}
          profiles={profiles}
          copy={copy}
          lang={lang}
          onClose={() => setSelected(null)}
        />
      )}
    </div>
  );
}

