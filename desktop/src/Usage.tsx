function fmtTokens(n: number): string {
  if (!Number.isFinite(n) || n <= 0) return "0";
  if (n >= 1e9) return (n / 1e9).toFixed(2) + "B";
  if (n >= 1e6) return (n / 1e6).toFixed(1) + "M";
  if (n >= 1e3) return (n / 1e3).toFixed(1) + "K";
  return String(Math.round(n));
}

function fmtPercent(v: number): string {
  if (!Number.isFinite(v)) return "0%";
  return (v * 100).toFixed(v >= 0.995 ? 0 : 1) + "%";
}

function hitTone(rate: number): "high" | "mid" | "low" {
  if (rate >= 0.8) return "high";
  if (rate >= 0.5) return "mid";
  return "low";
}

function hitColor(rate: number): string {
  const tone = hitTone(rate);
  if (tone === "high") return "#16a34a";
  if (tone === "mid") return "#d97706";
  return "#dc2626";
}

function timeAgo(ts: number, lang: "zh" | "en"): string {
  if (!ts) return "—";
  const diff = Math.max(0, Math.floor(Date.now() / 1000) - ts);
  const zh = lang === "zh";
  if (diff < 60) return zh ? "刚刚" : "just now";
  if (diff < 3600) {
    const m = Math.floor(diff / 60);
    return zh ? m + " 分钟前" : m + "m ago";
  }
  if (diff < 86400) {
    const h = Math.floor(diff / 3600);
    return zh ? h + " 小时前" : h + "h ago";
  }
  const d = Math.floor(diff / 86400);
  if (d < 30) return zh ? d + " 天前" : d + "d ago";
  return new Date(ts * 1000).toLocaleDateString();
}

